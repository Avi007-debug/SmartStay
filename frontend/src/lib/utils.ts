import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

export function isAiGeneratedDescription(pg: any): boolean {
  if (!pg) return false;

  // 1. Direct explicit flag
  if (pg.is_ai_generated === true) return true;

  // 2. Flag inside rules (handle both object and serialized JSON string)
  let rulesObj = pg.rules;
  if (typeof rulesObj === 'string') {
    try {
      rulesObj = JSON.parse(rulesObj);
    } catch {
      // If it's a raw string containing the flag
      if (rulesObj.includes('"is_ai_generated":true') || rulesObj.includes('"is_ai_generated": true')) {
        return true;
      }
    }
  }
  if (rulesObj && typeof rulesObj === 'object' && rulesObj.is_ai_generated === true) {
    return true;
  }

  // 3. Fallback heuristic for older listings generated by AI before the flag was stored in rules
  const desc = (pg.description || '').trim();
  if (!desc || desc.length < 60) return false;

  const aiPatterns = [
    /welcome to/i,
    /conveniently located/i,
    /strategically located/i,
    /ideally located/i,
    /prime location/i,
    /students and (working )?professionals/i,
    /(working )?professionals and students/i,
    /students or working professionals/i,
    /perfect blend of/i,
    /seamless blend of/i,
    /comfortable (and convenient|living)/i,
    /convenient and comfortable/i,
    /home away from home/i,
    /modern amenities/i,
    /tailored (for|to)/i,
    /catering to/i,
    /peace of mind/i,
    /hassle-free/i,
    /look no further/i,
    /nestled in/i,
    /vibrant community/i
  ];

  const hasAiEmoji = /[✨🌟🏡🛋️📍🍳🛏️]/.test(desc);
  const matchCount = aiPatterns.reduce((count, pattern) => count + (pattern.test(desc) ? 1 : 0), 0);

  if (hasAiEmoji && matchCount >= 1) return true;
  if (matchCount >= 2) return true;
  if (matchCount >= 1 && desc.length >= 100 && /(welcome to|perfect blend of|students and (working )?professionals|conveniently located|comfortable living)/i.test(desc)) {
    return true;
  }

  return false;
}
